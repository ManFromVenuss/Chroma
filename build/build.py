#!/usr/bin/env python3
"""Concatenate src/ into a self-contained dist/main.lua.

Each source file becomes a factory function in a module table, keyed by its path
without the .lua extension, and receives the require shim as its only argument.
This is exactly the wrapping tests/harness.lua applies, so identical text runs
locally under Lua 5.4 and in-game under Luau.

  python build/build.py            # write dist/main.lua
  python build/build.py --install  # also copy to the Potassium workspace
"""

import argparse
import os
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "src"
DIST = REPO / "dist"
VERSION = "0.1.0"

WORKSPACE = Path(os.path.expandvars(r"%LOCALAPPDATA%")) / "Potassium" / "workspace"

# Order is irrelevant to correctness because require() resolves lazily, but a
# stable order keeps the diff readable between builds.
def module_paths():
    return sorted(
        p.relative_to(SRC).with_suffix("").as_posix()
        for p in SRC.rglob("*.lua")
    )


def build():
    parts = [
        f"-- Chroma {VERSION} -- generated by build/build.py, do not edit\n",
        "local __modules = {}\n",
        "local __cache = {}\n",
        "local function __require(path)\n",
        "    local hit = __cache[path]\n",
        "    if hit ~= nil then return hit end\n",
        "    local factory = __modules[path]\n",
        "    if not factory then\n",
        '        error("chroma: unknown module \'" .. tostring(path) .. "\'", 2)\n',
        "    end\n",
        "    local result = factory(__require)\n",
        "    __cache[path] = result\n",
        "    return result\n",
        "end\n\n",
    ]

    for path in module_paths():
        text = (SRC / f"{path}.lua").read_text(encoding="utf-8")
        parts.append(f'__modules["{path}"] = function(require)\n')
        parts.append(text)
        if not text.endswith("\n"):
            parts.append("\n")
        parts.append("end\n\n")

    parts.append('return __require("init")\n')

    DIST.mkdir(exist_ok=True)
    out = DIST / "main.lua"
    out.write_text("".join(parts), encoding="utf-8")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--install", action="store_true",
                    help="copy the built file into the Potassium workspace")
    args = ap.parse_args()

    out = build()
    count = len(module_paths())
    print(f"built {out.relative_to(REPO)}  ({count} modules, {out.stat().st_size // 1024} KB)")

    if args.install:
        if not WORKSPACE.is_dir():
            print(f"workspace not found: {WORKSPACE}", file=sys.stderr)
            return 1
        dest = WORKSPACE / "chroma_dist.lua"
        shutil.copy2(out, dest)
        print(f"installed to {dest}")

        # The dev harness ships alongside the bundle. Copying only the bundle
        # left a stale harness in the workspace for a whole milestone, and the
        # symptom -- a page simply missing in-game -- looked like a library bug
        # rather than an out-of-date file.
        harness = REPO / "dev" / "harness.lua"
        harness_dest = WORKSPACE / "chroma_dev.lua"
        shutil.copy2(harness, harness_dest)
        print(f"installed to {harness_dest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
